let currentPage = -1;
let currentLanguage = "ru";

const intro = document.getElementById("intro");

const storySection =
    document.getElementById("storySection");

const backBtn =
    document.getElementById("backBtn");

const nextBtn =
    document.getElementById("nextBtn");

const photoGallery =
    document.getElementById("photoGallery");

const storyText =
    document.getElementById("storyText");

const pageCounter =
    document.getElementById("pageCounter");


// ==========================================
// 4. LANGUAGE SWITCH
// ==========================================

function toggleLanguage() {

    currentLanguage =
        currentLanguage === "ru" ? "uz" : "ru";

    document.getElementById("langBtn").textContent =
        currentLanguage === "ru" ? "O'Z" : "РУ";

    document.documentElement.lang = currentLanguage;

    updateLanguage();

    renderPage();

}


function updateLanguage() {

    const t = translations[currentLanguage];

    document.querySelectorAll("[data-i18n]").forEach(element => {

        const key = element.dataset.i18n;

        if (t[key]) {

            element.textContent = t[key];

        }

    });

}


// ==========================================
// 5. PAGE RENDERING
// ==========================================

function renderPage() {

    const t = translations[currentLanguage];

    // Intro page

    if (currentPage === -1) {

        intro.classList.add("active");

        storySection.classList.remove("active");

        backBtn.classList.add("hidden");

        return;

    }


    // Story page

    intro.classList.remove("active");

    storySection.classList.add("active");

    backBtn.classList.remove("hidden");


    const page = pages[currentPage];


    // Page counter

    pageCounter.textContent =
        `${t.page} ${currentPage + 1} / ${pages.length}`;


    // Reset gallery

    photoGallery.innerHTML = "";

    photoGallery.className = "photo-gallery";


    if (page.images.length === 1) {

        photoGallery.classList.add("one-photo");

    }

    if (page.images.length === 3) {

        photoGallery.classList.add("three-photos");

    }

    if (page.images.length === 5) {

        photoGallery.classList.add("five-photos");

    }


    // Display photos

    page.images.forEach((imageName, index) => {

        const card = document.createElement("div");

        card.className = "photo-card";

        card.style.animationDelay = `${index * 0.12}s`;


        const img = document.createElement("img");

        img.src = `assets/${imageName}`;

        img.alt = imageName;

        img.loading = "lazy";


        img.onclick = () => {

            openLightbox(`assets/${imageName}`);

        };


        img.onerror = () => {

            card.innerHTML = `
                <div style="
                    padding:35px 10px;
                    color:#bd426f;
                    font-size:13px;
                ">
                    Rasm topilmadi:<br>
                    ${imageName}
                </div>
            `;

        };


        card.appendChild(img);

        photoGallery.appendChild(card);

    });


    // Story text

    storyText.textContent =
        t.stories[currentPage];


    // Next button

    if (currentPage === pages.length - 1) {

        nextBtn.textContent = t.final;

        nextBtn.disabled = true;

        nextBtn.style.opacity = "0.8";

        nextBtn.style.cursor = "default";

    } else {

        nextBtn.textContent = t.next + " →";

        nextBtn.disabled = false;

        nextBtn.style.opacity = "1";

        nextBtn.style.cursor = "pointer";

    }


    // Scroll to top

    window.scrollTo({

        top: 0,

        behavior: "smooth"

    });

}


// ==========================================
// 6. NEXT PAGE
// ==========================================

function nextPage() {

    if (currentPage < pages.length - 1) {

        currentPage++;

        renderPage();

    }

}


// ==========================================
// 7. PREVIOUS PAGE
// ==========================================

function previousPage() {

    if (currentPage > 0) {

        currentPage--;

        renderPage();

    } else if (currentPage === 0) {

        currentPage = -1;

        renderPage();

    }

}


// ==========================================
// 8. IMAGE LIGHTBOX
// ==========================================

function openLightbox(src) {

    const lightbox =
        document.getElementById("lightbox");

    const lightboxImage =
        document.getElementById("lightboxImage");

    const downloadBtn =
        document.getElementById("downloadBtn");


    lightboxImage.src = src;

    downloadBtn.href = src;

    downloadBtn.setAttribute(
        "download",
        src.split("/").pop()
    );


    lightbox.classList.add("active");

    document.body.style.overflow = "hidden";

}


// ==========================================
// 9. CLOSE LIGHTBOX
// ==========================================

function closeLightbox(event) {

    if (

        !event ||

        event.target.id === "lightbox" ||

        event.target.classList.contains("close-lightbox")

    ) {

        document.getElementById("lightbox")
            .classList.remove("active");

        document.body.style.overflow = "";

    }

}


// Escape key

document.addEventListener("keydown", event => {

    if (event.key === "Escape") {

        closeLightbox();

    }

});


// ==========================================
// 10. FLOATING HEARTS
// ==========================================

function createHearts() {

    const container =
        document.getElementById("hearts");


    for (let i = 0; i < 15; i++) {

        const heart = document.createElement("div");

        heart.className = "floating-heart";

        heart.textContent = "♥";

        heart.style.left =
            Math.random() * 100 + "%";

        heart.style.animationDuration =
            (8 + Math.random() * 12) + "s";

        heart.style.animationDelay =
            (Math.random() * 10) + "s";

        heart.style.fontSize =
            (12 + Math.random() * 20) + "px";


        container.appendChild(heart);

    }

}


